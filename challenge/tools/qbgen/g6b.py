def ds(f, nd=2):
    """Fraction -> 十进制字符串，去掉小数尾零"""
    s = ("%." + str(nd) + "f") % float(f)
    s = s.rstrip("0").rstrip(".")
    return s if s else "0"


def up(n, k):
    """n 除以 k 向上取整"""
    return -(-n // k)



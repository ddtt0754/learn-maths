def simp(n):
    """n = k²·m，返回 (k, m)，m 无平方因子"""
    k = 1
    i = 2
    while i * i <= n:
        while n % (i * i) == 0:
            n //= i * i
            k *= i
        i += 1
    return k, n


def avg(data):
    return sum(data) // len(data)


def var(data):
    m = sum(data) / len(data)
    v = sum((x - m) ** 2 for x in data) / len(data)
    return int(v) if v == int(v) else round(v, 2)


